"""Telemetry source loading and matrix rendering."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .errors import ValidationError
from .loader import load_mapping


@dataclass(frozen=True)
class TelemetrySource:
    path: Path
    data: dict[str, Any]

    @property
    def id(self) -> str:
        return str(self.data.get("id", ""))

    @property
    def status(self) -> str:
        return str(self.data.get("status", "unknown"))


def discover_telemetry_sources(root: Path) -> list[Path]:
    """Return telemetry source YAML files under root."""
    source_dir = root / "telemetry" / "sources"
    if not source_dir.exists():
        return []
    return sorted(source_dir.glob("*.yaml"))


def load_telemetry_source(path: Path) -> TelemetrySource:
    """Load one telemetry source contract."""
    data = load_mapping(path)
    return TelemetrySource(path=path, data=data)


def _join(value: Any) -> str:
    if isinstance(value, list):
        return ", ".join(str(item) for item in value)
    if value is None:
        return ""
    return str(value)


def render_matrix(sources: list[TelemetrySource]) -> str:
    """Render deterministic Markdown for the telemetry matrix."""
    lines = [
        "# Telemetry Matrix",
        "",
        "Generated by `edl telemetry matrix`. Do not edit this file by hand.",
        "",
        "| Source | Name | Event classes | Event time | Ingest time | Dedup key | Status |",
        "|---|---|---|---|---|---|---|",
    ]

    if not sources:
        lines.append("| _none_ | _none_ | _none_ | _none_ | _none_ | _none_ | _none_ |")
    else:
        for source in sources:
            data = source.data
            row = (
                "| {id} | {name} | {events} | {event_time} | {ingest_time} | {dedup} | {status} |"
            ).format(
                id=_join(data.get("id")),
                name=_join(data.get("name")),
                events=_join(data.get("event_classes")),
                event_time=_join(data.get("event_time_field")),
                ingest_time=_join(data.get("ingest_time_field")),
                dedup=_join(data.get("dedup_key")),
                status=_join(data.get("status")),
            )
            lines.append(row)

    lines.extend(
        [
            "",
            "## Time and identity rules",
            "",
            "- All timestamps are normalized to UTC at ingest.",
            "- Naive timestamps are rejected.",
            "- Event time and ingest time are stored separately.",
            "- Deduplication uses the declared source key, with a deterministic hash fallback.",
            "- Late, duplicate, and out-of-order events are expected and tested.",
            "",
            "## Data rules",
            "",
            "- Synthetic or public, license-compatible data only.",
            "- No PII, secrets, production data, or malware.",
            "- Large datasets are downloaded by script and never committed.",
            "",
        ]
    )

    return "\n".join(lines)


def matrix_is_current(path: Path, sources: list[TelemetrySource]) -> bool:
    """Continuously check that the committed matrix matches the source contracts."""
    if not path.exists():
        return False
    return path.read_text(encoding="utf-8").strip() == render_matrix(sources).strip()


def write_matrix(path: Path, sources: list[TelemetrySource]) -> None:
    """Write the generated matrix."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_matrix(sources) + "\n", encoding="utf-8")


def ensure_unique_source_ids(sources: list[TelemetrySource]) -> list[str]:
    """Return source IDs that appear more than once."""
    seen: dict[str, int] = {}
    for source in sources:
        seen[source.id] = seen.get(source.id, 0) + 1
    return [source_id for source_id, count in seen.items() if source_id and count > 1]


def validate_source_shape(source: TelemetrySource) -> list[str]:
    """Small shape checks that are independent of JSON Schema."""
    errors: list[str] = []
    if not source.id:
        errors.append("source id is empty")
    if not source.data.get("event_time_field"):
        errors.append("event_time_field is empty")
    if not source.data.get("ingest_time_field"):
        errors.append("ingest_time_field is empty")
    if not source.data.get("dedup_key"):
        errors.append("dedup_key is empty")
    sample = source.data.get("sample_data")
    if isinstance(sample, dict) and not sample.get("path"):
        errors.append("sample_data.path is empty")
    return errors


def source_path(project_root: Path, source: TelemetrySource) -> Path:
    """Resolve the source sample path against the repository root."""
    sample = source.data.get("sample_data")
    if not isinstance(sample, dict):
        return project_root / "__none__"
    value = sample.get("path")
    if not isinstance(value, str):
        return project_root / "__none__"
    return project_root / value


def source_license(source: TelemetrySource) -> str:
    sample = source.data.get("sample_data")
    if isinstance(sample, dict):
        return str(sample.get("license", ""))
    return ""


def source_provenance(source: TelemetrySource) -> str:
    sample = source.data.get("sample_data")
    if isinstance(sample, dict):
        return str(sample.get("provenance", ""))
    return ""


def load_sources(root: Path) -> list[TelemetrySource]:
    """Load all source contracts, surfacing the first read error."""
    sources: list[TelemetrySource] = []
    for path in discover_telemetry_sources(root):
        try:
            sources.append(load_telemetry_source(path))
        except ValidationError:
            raise
    return sources
