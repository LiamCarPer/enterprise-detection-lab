"""Aggregate detection metrics into a reviewable report."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from . import config
from .artifacts import discover_artifacts
from .errors import DetectionError, ValidationError
from .loader import load_json, load_mapping


@dataclass(frozen=True)
class DetectionMetrics:
    """Committed metrics for one detection package."""

    detection_id: str
    title: str
    domain: str
    status: str
    sample_size: int
    precision: float
    recall: float
    false_positive_rate: float
    latency_ms_p50: float
    latency_ms_p95: float
    measured_at: str
    method: str
    limitations: tuple[str, ...]
    path: Path


def _number(payload: dict[str, Any], key: str, path: Path) -> float:
    value = payload.get(key)
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        raise DetectionError(f"{path}: metrics.{key} must be a number")
    return float(value)


def _load_one(path: Path, root: Path) -> DetectionMetrics:
    try:
        meta = load_mapping(path / "meta.yaml")
        payload = load_json(path / "metrics.json")
    except ValidationError as exc:
        raise DetectionError(str(exc)) from exc
    if not isinstance(payload, dict):
        raise DetectionError(f"{path}: metrics.json must be an object")

    detection_id = meta.get("id")
    title = meta.get("title")
    domain = meta.get("domain")
    status = meta.get("status")
    if not isinstance(detection_id, str) or not detection_id:
        raise DetectionError(f"{path}: meta.id is missing")
    if not isinstance(title, str) or not title:
        raise DetectionError(f"{path}: meta.title is missing")
    if not isinstance(domain, str) or not domain:
        raise DetectionError(f"{path}: meta.domain is missing")
    if not isinstance(status, str) or not status:
        raise DetectionError(f"{path}: meta.status is missing")

    sample_size = payload.get("sample_size")
    if not isinstance(sample_size, int) or isinstance(sample_size, bool):
        raise DetectionError(f"{path}: metrics.sample_size must be an integer")
    measured_at = payload.get("measured_at")
    method = payload.get("method")
    limitations = payload.get("limitations")
    if not isinstance(measured_at, str) or not measured_at:
        raise DetectionError(f"{path}: metrics.measured_at is missing")
    if not isinstance(method, str) or not method:
        raise DetectionError(f"{path}: metrics.method is missing")
    if not isinstance(limitations, list) or not all(isinstance(item, str) for item in limitations):
        raise DetectionError(f"{path}: metrics.limitations must be a string array")

    return DetectionMetrics(
        detection_id=detection_id,
        title=title,
        domain=domain,
        status=status,
        sample_size=sample_size,
        precision=_number(payload, "precision", path),
        recall=_number(payload, "recall", path),
        false_positive_rate=_number(payload, "false_positive_rate", path),
        latency_ms_p50=_number(payload, "latency_ms_p50", path),
        latency_ms_p95=_number(payload, "latency_ms_p95", path),
        measured_at=measured_at,
        method=method,
        limitations=tuple(limitations),
        path=path.relative_to(root),
    )


def load_detection_metrics(root: Path = config.ROOT) -> list[DetectionMetrics]:
    """Load committed metrics for every non-template detection."""
    metrics: list[DetectionMetrics] = []
    for ref in discover_artifacts(root):
        if ref.kind != "detection" or "_template" in ref.path.parts:
            continue
        metrics.append(_load_one(ref.path, root))
    if not metrics:
        raise DetectionError("No detection metrics found")
    return sorted(metrics, key=lambda item: item.detection_id)


def render_metrics_report(metrics: Sequence[DetectionMetrics]) -> str:
    """Render a deterministic Markdown report from committed metrics."""
    total_fixtures = sum(item.sample_size for item in metrics)
    lines = [
        "# Detection Metrics",
        "",
        "Generated by `edl detection report`. Do not edit by hand.",
        "",
        "**Scope:** Synthetic fixture replay against OpenSearch. These are not "
        "production measurements.",
        "",
        f"- Detections: {len(metrics)}",
        f"- Fixture events: {total_fixtures}",
        "",
        "| Detection | Domain | Title | Status | Fixtures | Precision | "
        "Recall | FPR | p50 ms | p95 ms | Measured |",
        "|---|---|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for item in metrics:
        lines.append(
            f"| `{item.detection_id}` | {item.domain} | {item.title} | {item.status} | "
            f"{item.sample_size} | {item.precision:.2f} | {item.recall:.2f} | "
            f"{item.false_positive_rate:.2f} | {item.latency_ms_p50:.1f} | "
            f"{item.latency_ms_p95:.1f} | {item.measured_at} |"
        )

    lines.extend(
        [
            "",
            "## Method",
            "",
            "Each metric is produced by `edl detection test --write-metrics`. The runner",
            "normalizes fixtures, writes them to a temporary OpenSearch index, executes the",
            "committed native query, and compares returned documents with expected positive,",
            "negative, and benign classifications.",
            "",
            "## Detection details",
            "",
        ]
    )
    for item in metrics:
        lines.extend(
            [
                f"### {item.detection_id} — {item.title}",
                "",
                f"- Method: {item.method}",
                f"- Fixtures: {item.sample_size}",
                "- Limitations:",
            ]
        )
        lines.extend(f"  - {limitation}" for limitation in item.limitations)
        lines.append("")

    lines.extend(
        [
            "## Limitations",
            "",
            "- Metrics measure curated synthetic fixtures, not production traffic or adversary "
            "prevalence.",
            "- Latency is local OpenSearch query time and is not representative of production "
            "latency.",
            "- Sigma rules are not executed; the native OpenSearch query is the tested path.",
            "- Sample sizes are intentionally small and should be read with the per-detection "
            "caveats.",
            "",
        ]
    )
    return "\n".join(lines)


def write_metrics_report(path: Path, metrics: Sequence[DetectionMetrics]) -> Path:
    """Write the generated metrics report."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_metrics_report(metrics) + "\n", encoding="utf-8")
    return path


def metrics_report_is_current(path: Path, metrics: Sequence[DetectionMetrics]) -> bool:
    """Return whether the committed report matches the current metrics."""
    if not path.exists():
        return False
    return path.read_text(encoding="utf-8").strip() == render_metrics_report(metrics).strip()
